const {initializeTestEnvironment,assertFails,assertSucceeds}=require('@firebase/rules-unit-testing');
const {doc,setDoc,getDoc,deleteDoc,updateDoc,writeBatch}=require('firebase/firestore');
const fs=require('node:fs');
const test=require('node:test');
test('Trip wallet authorization',async()=>{
 const env=await initializeTestEnvironment({projectId:'demo-trip-wallet',firestore:{rules:fs.readFileSync('firestore.rules','utf8')}});
 const path=(c,id)=>'trips/main/'+c+'/'+id;
 const ctx=(id,email)=>env.authenticatedContext(id,{email,email_verified:true}).firestore();
 const a=ctx('a','a@example.com'), outsider=ctx('x','x@example.com'), admin=ctx('p','singuluripranay@gmail.com');
 const e={desc:'Gas',amount:1000,paidBy:'A',split:['A','P'],date:'2026-12-24',by:'A',at:'2026-12-24T00:00:00Z'};
 try {
 await env.clearFirestore();
 await assertFails(setDoc(doc(outsider,path('members','x')),{person:'A'}));
 const req={person:'M',email:'x@example.com',status:'pending',at:e.at};
 await assertFails(setDoc(doc(outsider,path('requests','other')),req));
 await assertFails(setDoc(doc(outsider,path('requests','x')),{...req,email:'fake@example.com'}));
 await assertFails(setDoc(doc(outsider,path('requests','x')),{...req,status:'approved'}));
 await assertSucceeds(setDoc(doc(outsider,path('requests','x')),req));
 await assertSucceeds(getDoc(doc(outsider,path('requests','x'))));
 await assertFails(getDoc(doc(a,path('requests','x'))));
 await assertFails(updateDoc(doc(outsider,path('requests','x')),{status:'rejected'}));
 await assertSucceeds(getDoc(doc(admin,path('requests','x'))));
 await assertSucceeds(updateDoc(doc(admin,path('requests','x')),{status:'rejected'}));
 await assertSucceeds(setDoc(doc(outsider,path('requests','x')),req));
 await assertFails(setDoc(doc(outsider,path('requests','x')),req));
 await assertFails(setDoc(doc(admin,path('members','x')),{person:'M'}));
 const approval=writeBatch(admin);approval.set(doc(admin,path('approvalSlots','M')),{uid:'x'});approval.set(doc(admin,path('members','x')),{person:'M'});approval.delete(doc(admin,path('requests','x')));await assertSucceeds(approval.commit());
 const y=ctx('y','y@example.com');await assertSucceeds(setDoc(doc(y,path('requests','y')),{...req,email:'y@example.com'}));
 const duplicate=writeBatch(admin);duplicate.set(doc(admin,path('approvalSlots','M')),{uid:'y'});duplicate.set(doc(admin,path('members','y')),{person:'M'});duplicate.delete(doc(admin,path('requests','y')));await assertFails(duplicate.commit());
 await assertFails(deleteDoc(doc(admin,path('approvalSlots','M'))));
 const reset=writeBatch(admin);reset.delete(doc(admin,path('members','x')));reset.delete(doc(admin,path('approvalSlots','M')));await assertSucceeds(reset.commit());
 await assertSucceeds(setDoc(doc(admin,path('members','a')),{person:'A'}));
 await assertFails(updateDoc(doc(a,path('members','a')),{person:'P'}));
 await assertSucceeds(setDoc(doc(a,path('expenses','e')),e));
 await assertFails(getDoc(doc(outsider,path('expenses','e'))));
 await assertFails(getDoc(doc(env.unauthenticatedContext().firestore(),path('expenses','e'))));
 for(const bad of [{amount:-1},{amount:1.5},{by:'P'},{split:['A','A']},{split:['X']},{split:[]},{paidBy:'X'},{currency:'CAD'}]) await assertFails(setDoc(doc(a,path('expenses','bad')),{...e,...bad}));
 await assertSucceeds(setDoc(doc(admin,path('members','b')),{person:'D'}));
 const b=ctx('b','b@example.com');
 await assertSucceeds(updateDoc(doc(b,path('expenses','e')),{amount:2}));
 await assertFails(updateDoc(doc(b,path('expenses','e')),{by:'D'}));
 await assertFails(updateDoc(doc(outsider,path('expenses','e')),{amount:3}));
 await assertFails(setDoc(doc(b,path('deleted','fake')),{by:'D',at:e.at}));
 await assertSucceeds(setDoc(doc(a,path('expenses','remove')),e));
 const batch=writeBatch(b);batch.delete(doc(b,path('expenses','remove')));batch.set(doc(b,path('deleted','remove')),{by:'D',at:e.at});await assertSucceeds(batch.commit());
 await assertSucceeds(updateDoc(doc(admin,path('expenses','e')),{amount:2000}));
 const p={from:'A',to:'P',amount:100,date:e.date,by:'A',at:e.at};
 await assertSucceeds(setDoc(doc(a,path('payments','p')),p));
 await assertFails(setDoc(doc(a,path('payments','bad')),{...p,from:'P',to:'A'}));
 await assertSucceeds(updateDoc(doc(b,path('payments','p')),{amount:200}));
 await assertFails(updateDoc(doc(b,path('payments','p')),{from:'D'}));
 const pb=writeBatch(b);pb.delete(doc(b,path('payments','p')));pb.set(doc(b,path('deleted','p')),{by:'D',at:e.at});await assertSucceeds(pb.commit());
 const l={who:'A',act:'added',text:'Gas',at:e.at};
 await assertSucceeds(setDoc(doc(a,path('log','l')),l));
 await assertFails(setDoc(doc(a,path('log','bad')),{...l,who:'P'}));
 await assertFails(deleteDoc(doc(admin,path('log','l'))));
 await assertSucceeds(deleteDoc(doc(admin,path('members','a'))));
 await assertFails(getDoc(doc(a,path('expenses','e'))));
 } finally {await env.cleanup();}
});
